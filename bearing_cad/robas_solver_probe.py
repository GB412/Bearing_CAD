"""Local Windows-only RoBAS_v2.exe protocol probe (NOT a CAD solver API).

Source: BallBearingAnalysis.cs / CylinderBearingAnalysis.cs use exe/DATA.txt,
launch RoBAS_v2.exe with cwd=exe, and read exe/OUT.txt. The user-provided
RoBAS_Resources.zip has the executable but no DATA.txt reference case.

This tool validates legacy quasi-static DATA.txt record order and runs the
exact source-archive executable in a NEW isolated workspace. It never
generates physical solver inputs from CAD parameters, parses engineering
results, or claims convergence. No executable or original data are bundled.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import platform
import re
import shutil
import struct
import subprocess
import sys
import uuid

# SHA-256 of RoBAS_Resources.zip: RoBAS_Resources/exe/RoBAS_v2.exe.
# Only this known original user-provided x86 binary is eligible for execution.
ORIGINAL_ROBAS_EXE_SHA256 = (
    "0449dbade9f97da768961e7cd8af3277b8a6fbf2bf8a2b2c9c23784caac11829"
)
_SOURCE_FIRST = (
    "rec 1", "rec 2.1", "rec 2.2", "rec 2.3", "rec 3.1",
    "rec 3.2", "rec 3.3", "rec 3.4", "rec 3.5", "rec 4",
)
_SOURCE_COMMON_TAIL = (
    "rec 7.0", "rec 7.1", "rec 7.2.x", "rec 7.2.x",
    "rec 8.1", "rec 8.2.1", "rec 8.2.2", "rec 8.3", "rec 8.4",
    "rec 8.5", "rec 8.6.0", "rec 8.6.1", "rec 8.6.2",
    "rec 8.6.3", "rec 8.6.4", "rec 8.6.5", "rec 8.6.6",
    "rec 9.0", "rec 9.1.1", "rec 9.1.2", "rec 9.1.3",
    "rec 9.2", "rec 9.5", "rec 9.6", "rec 9.7",
    "rec 10.0", "rec 10.1C", "rec 10.3", "rec 10.5.1B",
    "rec 10.5.2B", "rec 10.6", "rec 11",
)
_RECORDS = {
    "ball": _SOURCE_FIRST + ("rec 5A",) + _SOURCE_COMMON_TAIL,
    "roller": _SOURCE_FIRST + ("rec 5B.1", "rec 5B.2") + _SOURCE_COMMON_TAIL,
}
_RECORD_RE = re.compile(r"^'(?P<label>rec [A-Za-z0-9.]+)',")
_MAX_INPUT = 256_000
_MAX_EXE = 20_000_000
_MAX_OUTPUT = 100_000_000


class SolverProbeError(ValueError):
    """Invalid or unverifiable original RoBAS solver input/source."""


def _sha_file(path: Path) -> str:
    digest = sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def inspect_executable(resources: str | Path, *,
                       expected_sha: str = ORIGINAL_ROBAS_EXE_SHA256) -> dict:
    """Verify MZ/PE x86 and *exact source-archive* digest before execution."""
    exe = Path(resources) / "exe" / "RoBAS_v2.exe"
    if exe.is_symlink() or not exe.is_file():
        raise SolverProbeError("Original RoBAS_Resources/exe/RoBAS_v2.exe is missing")
    size = exe.stat().st_size
    if not 512 <= size <= _MAX_EXE:
        raise SolverProbeError("Unexpected RoBAS_v2.exe file size")
    with exe.open("rb") as stream:
        head = stream.read(512)
    if head[:2] != b"MZ":
        raise SolverProbeError("RoBAS_v2.exe is not an MZ executable")
    pe_offset = struct.unpack_from("<I", head, 0x3c)[0]
    if pe_offset > size - 6:
        raise SolverProbeError("Invalid PE offset in RoBAS_v2.exe")
    with exe.open("rb") as stream:
        stream.seek(pe_offset)
        signature = stream.read(6)
    if signature[:4] != b"PE\x00\x00" or len(signature) != 6:
        raise SolverProbeError("RoBAS_v2.exe has no valid PE signature")
    machine = int.from_bytes(signature[4:6], "little")
    if machine != 0x014c:
        raise SolverProbeError("Original RoBAS_v2.exe is expected to be x86 (PE machine 0x014c)")
    digest = _sha_file(exe)
    if digest != expected_sha:
        raise SolverProbeError(
            "RoBAS_v2.exe SHA-256 differs from the user-provided original archive; "
            "do not execute an unverified binary")
    return {
        "relative_path": "exe/RoBAS_v2.exe",
        "sha256": digest, "size_bytes": size,
        "pe_machine": "x86",
        "verified_source_archive_binary": expected_sha == ORIGINAL_ROBAS_EXE_SHA256,
    }


def inspect_static_input(input_path: str | Path, *, family: str) -> dict:
    """Check original C# quasi-static record framing, not numerical validity."""
    if family not in _RECORDS:
        raise SolverProbeError("Family must be 'ball' or 'roller'")
    data_file = Path(input_path)
    if data_file.is_symlink() or not data_file.is_file():
        raise SolverProbeError("Provide a real DATA.txt generated by original RoBAS")
    if not 0 < data_file.stat().st_size <= _MAX_INPUT:
        raise SolverProbeError("Unexpected DATA.txt size")
    raw = data_file.read_bytes()
    if b"\0" in raw:
        raise SolverProbeError("DATA.txt contains binary NUL bytes")
    try:
        lines = raw.decode("utf-8-sig").splitlines()
    except UnicodeDecodeError as exc:
        raise SolverProbeError("DATA.txt must be UTF-8 as generated by C# StreamWriter") from exc
    expected = _RECORDS[family]
    if len(lines) != len(expected):
        raise SolverProbeError(
            f"Original {family} quasi-static DATA.txt must contain "
            f"{len(expected)} record lines, found {len(lines)}")
    for index, (line, label) in enumerate(zip(lines, expected), 1):
        matched = _RECORD_RE.match(line)
        if not matched or matched.group("label") != label:
            raise SolverProbeError(
                f"DATA.txt record {index} should start with '{label}', "
                "matching the source C# field order")
    mode = lines[0].split(",", 2)[1].strip()
    if mode != "-1":
        raise SolverProbeError("Only source quasi-static Mode=-1 is supported; dynamic analysis is unavailable")
    return {
        "family": family,
        "input_sha256": sha256(raw).hexdigest(),
        "size_bytes": len(raw), "record_count": len(lines),
        "protocol_status": "SOURCE_STATIC_RECORD_LABELS_MATCH",
        "numerical_fields_verified": False,
        "units_verified": False,
        "source": (
            "RoBAS/Core/BallBearing/BallBearingAnalysis.cs"
            if family == "ball" else
            "RoBAS/Core/RollerBearing/CylinderRollerBreaing/CylinderBearingAnalysis.cs"
        ),
    }


def inspect_probe(*, resources: str | Path, input_path: str | Path,
                  family: str, expected_sha: str = ORIGINAL_ROBAS_EXE_SHA256) -> dict:
    return {
        "schema_version": "bearing-cad.robas-solver-probe.v1",
        "stage": "source_preflight",
        "exe": inspect_executable(resources, expected_sha=expected_sha),
        "input": inspect_static_input(input_path, family=family),
        "solver_executed": False, "solver_converged": None,
        "engineering_approved": False,
    }


def _launch(exe: Path, workspace: Path, timeout_s: int) -> subprocess.CompletedProcess:
    with (workspace / "process.log").open("wb") as output:
        return subprocess.run(
            [str(exe)], cwd=workspace,
            stdin=subprocess.DEVNULL, stdout=output, stderr=subprocess.STDOUT,
            timeout=timeout_s, check=False, shell=False,
        )


def run_probe(*, resources: str | Path, input_path: str | Path,
              family: str, output_dir: str | Path, timeout_s: int = 300,
              expected_sha: str = ORIGINAL_ROBAS_EXE_SHA256,
              _launcher=None, _platform=None) -> dict:
    """Isolated Windows execution, output evidence only, not convergence."""
    if (_platform or platform.system()) != "Windows":
        raise SolverProbeError("Actual RoBAS_v2.exe execution is Windows-only")
    if type(timeout_s) is not int or not 1 <= timeout_s <= 3600:
        raise SolverProbeError("timeout_s must be between 1 and 3600 seconds")
    preflight = inspect_probe(
        resources=resources, input_path=input_path, family=family,
        expected_sha=expected_sha)
    output_root = Path(output_dir)
    if output_root.is_symlink():
        raise SolverProbeError("Refusing symlink output root")
    output_root.mkdir(parents=True, exist_ok=True)
    run_dir = output_root / ("run-" + uuid.uuid4().hex)
    run_dir.mkdir(mode=0o700)
    # Never modify or delete original resources/exe or user's DATA.txt.
    shutil.copyfile(Path(resources) / "exe" / "RoBAS_v2.exe", run_dir / "RoBAS_v2.exe")
    shutil.copyfile(input_path, run_dir / "DATA.txt")
    if _sha_file(run_dir / "RoBAS_v2.exe") != preflight["exe"]["sha256"]:
        raise SolverProbeError("Copied RoBAS executable digest changed")
    if _sha_file(run_dir / "DATA.txt") != preflight["input"]["input_sha256"]:
        raise SolverProbeError("Copied solver input digest changed")
    report = {
        **preflight, "stage": "isolated_execution",
        "run_directory": str(run_dir),
        "solver_executed": False, "solver_converged": None,
        "process_exit_code": None, "output_status": "NOT_EXECUTED",
        "output_files": [],
    }
    try:
        runner = _launcher or _launch
        report["solver_executed"] = True
        completed = runner(run_dir / "RoBAS_v2.exe", run_dir, timeout_s)
        report["process_exit_code"] = completed.returncode
        output = run_dir / "OUT.txt"
        if completed.returncode != 0:
            report["output_status"] = "PROCESS_NONZERO_EXIT"
        elif output.is_file() and not output.is_symlink() and 0 < output.stat().st_size <= _MAX_OUTPUT:
            report["output_status"] = "OUTPUT_PRESENT_UNPARSED_NOT_CONVERGENCE_PROOF"
        else:
            report["output_status"] = "OUTPUT_ABSENT_OR_INVALID"
    except subprocess.TimeoutExpired:
        report["output_status"] = "PROCESS_TIMEOUT"
    except OSError as exc:
        report["solver_executed"] = False
        report["output_status"] = "PROCESS_START_FAILED"
        report["process_error"] = type(exc).__name__
    for name in ("OUT.txt", "PRINT.txt", "a0_Final", "process.log"):
        path = run_dir / name
        if path.is_file() and not path.is_symlink() and path.stat().st_size <= _MAX_OUTPUT:
            report["output_files"].append({
                "filename": name, "sha256": _sha_file(path),
                "size_bytes": path.stat().st_size,
            })
    (run_dir / "solver_probe_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="RoBAS source input and local Windows solver probe")
    parser.add_argument("action", choices=("inspect", "run"))
    parser.add_argument("--resources", required=True, type=Path,
                        help="Local original RoBAS_Resources folder (NEVER commit)")
    parser.add_argument("--input", required=True, type=Path,
                        help="DATA.txt exported by original RoBAS; not auto-generated")
    parser.add_argument("--family", choices=("ball", "roller"), required=True)
    parser.add_argument("--out", type=Path, default=Path("artifacts/solver-probe"))
    parser.add_argument("--timeout", type=int, default=300)
    args = parser.parse_args(argv)
    try:
        result = (inspect_probe(resources=args.resources, input_path=args.input,
                                family=args.family)
                  if args.action == "inspect" else
                  run_probe(resources=args.resources, input_path=args.input,
                            family=args.family, output_dir=args.out,
                            timeout_s=args.timeout))
    except (SolverProbeError, OSError) as exc:
        print("RoBAS solver probe rejected: " + str(exc), file=sys.stderr)
        return 2
    print(json.dumps(result, ensure_ascii=False, indent=2))
    if args.action == "run" and result["output_status"] != "OUTPUT_PRESENT_UNPARSED_NOT_CONVERGENCE_PROOF":
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
